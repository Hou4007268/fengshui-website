### 六、非空间场景问答

【租房优化】
- 租房做可逆、低成本动作：动线收口、照明分层、软隔断、收纳优化。

【办公/事业】
- 办公桌朝向：先看主视线（面对门或窗）和背靠（实墙），再调细节。
- 商铺风水：收银台与动线实操，先止漏损再做增长。
- 办公室座位背后是过道：加高椅背或放矮柜，制造"靠山"感。
- 背对门坐（领导常见）：在身后放泰山石或书架，增加安全感。

【情感/姻缘】
- 桃花位在不同年份不同。2026年一白桃花星在正北，在这个位置放鲜花或粉色物品。
- 卧室放成对物品（如一对蜡烛、一对枕头）有助感情。
- 床头柜只放一边：容易导致夫妻关系不平衡，两边都放且保持整洁。

【财运/招财】
- 明财位（进门对角线）保持干净明亮，放招财绿植（发财树、金钱树）。
- 收纳原则：有进有出，定期清理旧物，不要让财位被杂物堵住。
- 钱包风水：长款钱包比折叠钱包好，保持整洁不塞满收据。

【学业/文昌】
- 文昌位（四绿星方位）2026年在正东，书桌朝向或在此方位放文昌塔/四支毛笔。
- 书桌不靠窗、不背门、不面对墙，理想是面向门窗方向、背靠实墙。

【健康/养生】
- 卧室镜子对床影响睡眠，移镜或遮挡。
- 床头不靠厕所墙：湿气重影响头部健康，换方向或加防潮层。
- 厨房保持整洁通风：灶台是"食禄"之源，脏乱直接影响家运。

