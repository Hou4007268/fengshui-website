## 常见问题知识库

### 一、空间风水

【入户/大门】
- 大门朝向不理想不一定直接导致财运停滞。更关键的是入户动线、采光和收纳。建议先做入口清理与照明优化，观察7-14天。
- 入户门对电梯：可用玄关屏风、绿植缓冲、门槛石收口6个低成本方案。
- 门口风水避坑：先做4个动作（清理杂物、增加照明、设缓冲区、调门垫方向）。
- 大门对楼梯：向下漏财，向上压运。门槛石+屏风+地垫三件套可缓解。
- 门对门（两户门正对）：挂门帘或在门内侧放小型屏风，避免气场直冲。

【客厅/财位】
- 客厅财位通常在进门对角线位置。优先放长青绿植或可维护的摆件，不要堆满。
- 沙发对门：主位旋转45° + 缓冲区重建，改善停留感。
- 穿堂风：从穿透动线改成分段停留，用软隔断或家具断开直冲。
- 客厅横梁压顶：沙发或茶几避开横梁正下方，用吊顶或灯光弱化。
- 电视对窗反光：调电视角度或加窗帘，避免"反光煞"影响情绪。
- 客厅太大太空旷：用地毯、绿植、柜体分区，增加"包裹感"。

【卧室/休息】
- 夫妻卧室：从睡眠区、收纳区、沟通区三步优化关系稳定度。
- 床头靠窗：不一定换床位，先做靠背和遮光系统（床头板+遮光帘）。
- 卫生间对卧室：先做门线管理和气味控制，再做进阶改造。
- 镜子对床：移镜子或加帘遮挡，夜间反射影响睡眠质量。
- 床下堆杂物：清理后空气流通改善，间接提升睡眠。
- 儿童房书桌：面向门或窗的方向坐，背后靠墙，利于专注。
- 主卧带卫生间：门常关+排气扇常开+门口放吸水垫，三步控场。

【厨房/灶台】
- 开门见灶：7个可立即执行的方法（屏风挡、移灶位、改门向、挂帘等）。
- 灶台朝向：动线优先，朝向其次，分阶段改造。
- 灶台对水槽（水火相冲）：中间放木质砧板或绿植做缓冲。
- 厨房在西北位（火烧天门）：用土元素（陶瓷、黄色调）泄火气。
- 冰箱对灶台：冰箱侧贴隔热贴或移位，避免冷热直冲。

【卫生间】
- 卫生间在房屋中心：门常关+排气常开+门上挂葫芦或水晶球。
- 卫生间门对床/对餐桌：同上处理+动线调整。
- 马桶对门：加屏风或帘，改不了格局就用视觉遮挡。

【阳台/窗外】
- 窗外有尖角（壁刀煞）：贴磨砂膜或挂凸面镜化解。
- 窗外有医院/殡仪馆：加强采光+厚窗帘遮挡+室内多放绿植。
- 阳台对高速路/高架桥：种高大绿植做缓冲带+关窗时用双层玻璃。

### 二、命理基础概念

【八字（四柱）基础】
- 八字由出生年、月、日、时四个时间点的天干地支组成，共八个字，故称"八字"或"四柱"。
- 十天干：甲乙（木）、丙丁（火）、戊己（土）、庚辛（金）、壬癸（水）。
- 十二地支：子丑寅卯辰巳午未申酉戌亥，对应十二生肖。
- 五行相生：木生火、火生土、土生金、金生水、水生木。
- 五行相克：木克土、土克水、水克火、火克金、金克木。
- 日主（日干）代表自己，其他七个字与日主的关系构成"十神"。
- 十神简解：比肩（同类）、劫财（竞争）、食神（才华）、伤官（叛逆）、偏财（横财）、正财（工资）、七杀（压力）、正官（规矩）、偏印（灵感）、正印（贵人）。
- 八字不是"缺什么补什么"，而是看整体格局的喜忌用神。缺水不一定需要补水，要看水在命局中是喜是忌。

【五行人格特征】
- 木型人：有主见、爱自由、做事有计划，但容易固执。适合创意、教育、管理。
- 火型人：热情、行动力强、社交好，但容易急躁。适合销售、公关、表演。
- 土型人：稳重、踏实、有耐心，但容易保守。适合财务、地产、农业。
- 金型人：果断、讲义气、重原则，但容易强硬。适合法律、军警、金融。
- 水型人：聪明、灵活、适应力强，但容易多变。适合贸易、传媒、IT。
- 大多数人是混合型，不是单一五行主导。

【紫微斗数基础】
- 紫微斗数是另一种主流命理体系，用出生时间排出十二宫位，每宫有不同星曜组合。
- 十二宫：命宫、兄弟宫、夫妻宫、子女宫、财帛宫、疾厄宫、迁移宫、交友宫、官禄宫、田宅宫、福德宫、父母宫。
- 十四主星简介：
  - 紫微：帝王星，领导力强，自尊心高
  - 天机：智囊星，思维敏捷，善策划
  - 太阳：光明星，热情博爱，适合服务行业
  - 武曲：财星，务实刚毅，善于理财
  - 天同：福星，温和善良，享乐主义
  - 廉贞：囚星，外冷内热，适合纪律部队
  - 天府：库星，稳重保守，善于积累
  - 太阴：富星，温柔细腻，财运好
  - 贪狼：桃花星，多才多艺，欲望强
  - 巨门：暗星，口才好但易招是非
  - 天相：印星，忠厚老实，辅佐型
  - 天梁：荫星，成熟稳重，有长辈缘
  - 七杀：将星，冲劲足，适合开拓
  - 破军：耗星，开创力强，变动多
- 命宫主星决定核心性格，其他宫位看对应领域的运势。
- 大运（十年一运）和流年（每年）会叠加影响命盘。

【纳音五行】
- 六十甲子每两年一组配一个纳音五行，如"甲子乙丑海中金"。
- 纳音反映的是年柱的五行属性，可以作为性格和运势的参考维度。
- 常见纳音举例：海中金、炉中火、大林木、路旁土、剑锋金、山头火、涧下水等。

### 三、风水核心概念

【峦头与理气】
- 风水分两大派：峦头派看外形（山势、水流、建筑形状），理气派看方位和时间（飞星、三元九运）。
- 实际操作中两者结合：先看峦头有没有明显问题，再用理气细化调整。

【三元九运】
- 每20年为一运，三运60年为一元，三元180年一个大循环。
- 当前是下元八运（2004-2023）转九运（2024-2043），九运属火，南方旺运。
- 九运期间：正南方位最旺，电子、文化、美容、能源行业利好。

【飞星基础】
- 九宫飞星：一白到九紫，每年飞星入中宫后按固定轨迹飞布九宫。
- 吉星：一白（桃花/人缘）、四绿（文昌/学业）、六白（权贵/事业）、八白（正财/置业）、九紫（喜庆/姻缘）。
- 凶星：二黑（病符）、三碧（是非）、五黄（大煞/意外）、七赤（破财/口舌）。
- 2026年飞星布局：五黄在正西，二黑在东南，需要在这两个方位放铜葫芦或六帝钱化解。

【常见煞气速查】
- 路冲煞：路直冲大门或窗户→挡（围墙、绿植、泰山石）
- 反弓煞：道路或河流反弓对着房子→挡（凸面镜、绿植）
- 壁刀煞：对面建筑的墙角直冲→贴磨砂膜、挂凸面镜
- 天斩煞：两栋楼之间的缝隙对着→窗帘遮挡+凸面镜
- 穿心煞：大门、阳台、后门一条线→隔断处理
- 尖角煞：对面有尖角物体→凸面镜或绿植挡
- 反光煞：玻璃幕墙反光入室→窗帘或磨砂膜

### 四、测试结果解读指南

【五行测试结果解读】
- 用户测出五行属性后常问"我缺X怎么办"。正确理解：五行缺某行不等于不好，关键看这个五行是你的"用神"还是"忌神"。
- 如果缺的是忌神，反而是好事。如果缺的是用神，才需要通过名字、方位、颜色、行业等补。
- 补五行的方法：名字加偏旁（如缺水用三点水旁字）、选对应颜色（木绿、火红、土黄、金白、水黑）、住对应方位、做对应行业。

【运势测试结果解读】
- 生肖运势是年柱层面的粗略参考，不能代表全部。完整运势需要结合八字四柱。
- "犯太岁"（本命年/冲太岁）不一定就差，要看八字整体格局。有些人犯太岁反而升职发财。
- 化解太岁的方法：拜太岁（正月）、佩戴太岁符、避免重大决策时冲动。

【面相测试结果解读】
- 面相是长期积累的状态反映，不是命定。心态和行为会改变面相。
- 常见面相说法：天庭饱满主聪慧、地阁方圆主晚运好、眉清目秀主人缘好。
- 面相可以改善：表情管理、作息调整、护肤保养对面相有正向影响。

【姓名测试结果解读】
- 姓名学主要看五格（天格、人格、地格、外格、总格）的数理吉凶和三才配置。
- 姓名只是辅助因素，不是决定性因素。好名字锦上添花，但不会雪中送炭。
- 改名建议：如果名字数理确实大凶+生活中确实不顺，可以考虑改名。否则不必过度在意。

【MBTI测试结果解读】
- MBTI是心理学性格分类工具，不是命理，但可以辅助了解自己的行为模式。
- 每种类型没有好坏之分，关键是在适合自己的环境中发挥优势。
- 可以结合命理分析：比如INTJ可能对应八字中偏印/七杀格局，ENFP可能对应食神/伤官格局。

